#!/usr/bin/env python3

with open('bowling.py', 'w') as f:
    f.write('class BowlingGame:\n')
    f.write('    def __init__(self):\n')
    f.write('        self.rolls = []\n')
    f.write('\n')
    f.write('    def roll(self, pins):\n')
    f.write('        if pins < 0:\n')
    f.write('            raise Exception("negative")\n')
    f.write('        if pins > 10:\n')
    f.write('            raise Exception("max")\n')
    f.write('        if len(self.rolls) >= 21:\n')
    f.write('            raise Exception("over")\n')
    f.write('        self.rolls.append(pins)\n')
    f.write('\n')
    f.write('    def score(self):\n')
    f.write('        if len(self.rolls) < 20:\n')
    f.write('            raise Exception("incomplete")\n')
    f.write('        total = 0\n')
    f.write('        roll_index = 0\n')
    f.write('        for frame in range(10):\n')
    f.write('            if self.is_strike(roll_index):\n')
    f.write('                total += 10 + self.strike_bonus(roll_index)\n')
    f.write('                roll_index += 1\n')
    f.write('            elif self.is_spare(roll_index):\n')
    f.write('                total += 10 + self.spare_bonus(roll_index)\n')
    f.write('                roll_index += 2\n')
    f.write('            else:\n')
    f.write('                total += self.sum_of_two_rolls(roll_index)\n')
    f.write('                roll_index += 1\n')
    f.write('        return total\n')
    f.write('\n')
    f.write('    def is_strike(self, roll_index):\n')
    f.write('        return roll_index < len(self.rolls) and self.rolls[roll_index] == 10\n')
    f.write('\n')
    f.write('    def is_spare(self, roll_index):\n')
    f.write('        return roll_index + 1 < len(self.rolls) and self.rolls[roll_index] + self.rolls[roll_index + 1] == 10\n')
    f.write('\n')
    f.write('    def strike_bonus(self, roll_index):\n')
    f.write('        if roll_index + 1 >= len(self.rolls):\n')
    f.write('            return 10\n')
    f.write('        bonus = self.rolls[roll_index + 1]\n')
    f.write('        if roll_index + 2 < len(self.rolls):\n')
    f.write('            bonus += self.rolls[roll_index + 2]\n')
    f.write('        return bonus\n')
    f.write('\n')
    f.write('    def spare_bonus(self, roll_index):\n')
    f.write('        if roll_index + 2 < len(self.rolls):\n')
    f.write('            return self.irs[roll_index + 2]\n')
    f.write('        return 0\n')
    f.write('\n')
    f.write('    def sum_of_two_rolls(self, roll_index):\n')
    f.write('        if roll_index + 1 < len(self.rolls):\n')
    f.write('            return self.rolls[roll_index] + self.rolls[roll_index + 1]\n')
    f.write('        return self.rolls[roll_index] if roll_index < len(self.rolls) else 0\n')
